-- =====================================================================
-- Migración 001: esquema inicial del POS
-- ---------------------------------------------------------------------
-- Crea todas las tablas del sistema. Usa "IF NOT EXISTS" para que se
-- pueda ejecutar sobre una base de datos que ya tiene las tablas sin
-- romper nada (por ejemplo, la base que ya usaba el equipo).
-- Requiere PostgreSQL 13 o superior (por gen_random_uuid()).
-- =====================================================================

-- ---------- Usuarios del sistema ----------
CREATE TABLE IF NOT EXISTS users (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username    VARCHAR(50)  NOT NULL UNIQUE,
  password    VARCHAR(255) NOT NULL,
  full_name   VARCHAR(100) NOT NULL,
  email       VARCHAR(100) UNIQUE,
  role        VARCHAR(20)  NOT NULL DEFAULT 'cashier',
  active      BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_user_role CHECK (role IN ('admin', 'cashier', 'waiter'))
);

-- ---------- Catálogo ----------
CREATE TABLE IF NOT EXISTS categories (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(100) NOT NULL UNIQUE,
  description TEXT,
  active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INTEGER NOT NULL,
  name        VARCHAR(120) NOT NULL,
  description TEXT,
  price       NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  sku         VARCHAR(50) UNIQUE,
  active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES categories(id)
);

-- ---------- Inventario de productos ----------
CREATE TABLE IF NOT EXISTS inventory (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id    INTEGER NOT NULL UNIQUE REFERENCES products(id),
  current_stock NUMERIC(12,2) NOT NULL DEFAULT 0,
  minimum_stock NUMERIC(12,2) NOT NULL DEFAULT 0,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_inventory_stock CHECK (current_stock >= 0 AND minimum_stock >= 0)
);

CREATE TABLE IF NOT EXISTS inventory_movements (
  id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  local_id       UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  product_id     INTEGER NOT NULL REFERENCES products(id),
  user_id        INTEGER NOT NULL REFERENCES users(id),
  movement_type  VARCHAR(20) NOT NULL,
  quantity       NUMERIC(12,2) NOT NULL,
  previous_stock NUMERIC(12,2) NOT NULL,
  new_stock      NUMERIC(12,2) NOT NULL,
  reason         TEXT,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_inventory_movement_quantity CHECK (quantity > 0),
  CONSTRAINT chk_inventory_movement_stock CHECK (previous_stock >= 0 AND new_stock >= 0),
  CONSTRAINT chk_inventory_movement_type CHECK (movement_type IN ('entry', 'exit', 'adjustment'))
);

-- ---------- Mesas y pedidos ----------
CREATE TABLE IF NOT EXISTS restaurant_tables (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_number INTEGER NOT NULL UNIQUE,
  capacity     INTEGER NOT NULL DEFAULT 4,
  status       VARCHAR(20) NOT NULL DEFAULT 'available',
  active       BOOLEAN NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_table_capacity CHECK (capacity > 0),
  CONSTRAINT chk_table_status CHECK (status IN ('available', 'occupied', 'reserved'))
);

CREATE TABLE IF NOT EXISTS orders (
  id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  local_id     UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  table_id     INTEGER REFERENCES restaurant_tables(id),
  user_id      INTEGER NOT NULL REFERENCES users(id),
  order_number VARCHAR(50) NOT NULL UNIQUE,
  order_type   VARCHAR(20) NOT NULL DEFAULT 'dine_in',
  status       VARCHAR(20) NOT NULL DEFAULT 'pending',
  notes        TEXT,
  subtotal     NUMERIC(12,2) NOT NULL DEFAULT 0,
  tax          NUMERIC(12,2) NOT NULL DEFAULT 0,
  total        NUMERIC(12,2) NOT NULL DEFAULT 0,
  created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_order_amounts CHECK (subtotal >= 0 AND tax >= 0 AND total >= 0),
  CONSTRAINT chk_order_status CHECK (status IN ('pending', 'preparing', 'ready', 'completed', 'cancelled')),
  CONSTRAINT chk_order_type CHECK (order_type IN ('dine_in', 'takeaway', 'delivery'))
);

CREATE TABLE IF NOT EXISTS order_items (
  id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id   BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id),
  quantity   INTEGER NOT NULL,
  unit_price NUMERIC(12,2) NOT NULL,
  subtotal   NUMERIC(12,2) NOT NULL,
  notes      TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  local_id   UUID NOT NULL DEFAULT gen_random_uuid(),
  CONSTRAINT uq_order_items_local_id UNIQUE (local_id),
  CONSTRAINT chk_order_item_prices CHECK (unit_price >= 0 AND subtotal >= 0),
  CONSTRAINT chk_order_item_quantity CHECK (quantity > 0)
);

-- ---------- Ventas y pagos ----------
CREATE TABLE IF NOT EXISTS payment_methods (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name   VARCHAR(50) NOT NULL UNIQUE,
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS sales (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  local_id    UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  order_id    BIGINT REFERENCES orders(id),
  user_id     INTEGER NOT NULL REFERENCES users(id),
  sale_number VARCHAR(50) NOT NULL UNIQUE,
  subtotal    NUMERIC(12,2) NOT NULL,
  tax         NUMERIC(12,2) NOT NULL DEFAULT 0,
  discount    NUMERIC(12,2) NOT NULL DEFAULT 0,
  total       NUMERIC(12,2) NOT NULL,
  status      VARCHAR(20) NOT NULL DEFAULT 'completed',
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_sale_amounts CHECK (subtotal >= 0 AND tax >= 0 AND discount >= 0 AND total >= 0),
  CONSTRAINT chk_sale_status CHECK (status IN ('completed', 'cancelled', 'refunded'))
);

CREATE TABLE IF NOT EXISTS sale_items (
  id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  sale_id      BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  product_id   INTEGER NOT NULL REFERENCES products(id),
  product_name VARCHAR(120) NOT NULL,
  quantity     INTEGER NOT NULL,
  unit_price   NUMERIC(12,2) NOT NULL,
  subtotal     NUMERIC(12,2) NOT NULL,
  local_id     UUID NOT NULL DEFAULT gen_random_uuid(),
  CONSTRAINT uq_sale_items_local_id UNIQUE (local_id),
  CONSTRAINT chk_sale_item_prices CHECK (unit_price >= 0 AND subtotal >= 0),
  CONSTRAINT chk_sale_item_quantity CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS payments (
  id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  local_id          UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  sale_id           BIGINT NOT NULL REFERENCES sales(id),
  payment_method_id INTEGER NOT NULL REFERENCES payment_methods(id),
  amount            NUMERIC(12,2) NOT NULL,
  reference         VARCHAR(100),
  status            VARCHAR(20) NOT NULL DEFAULT 'completed',
  created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_payment_amount CHECK (amount > 0),
  CONSTRAINT chk_payment_status CHECK (status IN ('pending', 'completed', 'failed', 'refunded'))
);

-- ---------- Ingredientes y proveedores ----------
CREATE TABLE IF NOT EXISTS units (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(50) NOT NULL UNIQUE,
  abbreviation VARCHAR(15) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS suppliers (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(120) NOT NULL,
  phone      VARCHAR(30),
  email      VARCHAR(100),
  address    TEXT,
  active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ingredients (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id INTEGER REFERENCES suppliers(id),
  unit_id     INTEGER NOT NULL REFERENCES units(id),
  name        VARCHAR(120) NOT NULL UNIQUE,
  description TEXT,
  active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ingredient_inventory (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ingredient_id INTEGER NOT NULL UNIQUE REFERENCES ingredients(id),
  current_stock NUMERIC(12,3) NOT NULL DEFAULT 0,
  minimum_stock NUMERIC(12,3) NOT NULL DEFAULT 0,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_ingredient_stock CHECK (current_stock >= 0 AND minimum_stock >= 0)
);

CREATE TABLE IF NOT EXISTS product_recipes (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id    INTEGER NOT NULL REFERENCES products(id),
  ingredient_id INTEGER NOT NULL REFERENCES ingredients(id),
  quantity      NUMERIC(12,3) NOT NULL,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_product_ingredient UNIQUE (product_id, ingredient_id),
  CONSTRAINT chk_recipe_quantity CHECK (quantity > 0)
);

-- ---------- Cajas registradoras ----------
CREATE TABLE IF NOT EXISTS cash_registers (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(80) NOT NULL UNIQUE,
  description TEXT,
  active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cash_register_sessions (
  id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  local_id         UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  cash_register_id INTEGER NOT NULL REFERENCES cash_registers(id),
  user_id          INTEGER NOT NULL REFERENCES users(id),
  opening_amount   NUMERIC(12,2) NOT NULL DEFAULT 0,
  closing_amount   NUMERIC(12,2),
  expected_amount  NUMERIC(12,2),
  difference       NUMERIC(12,2),
  status           VARCHAR(20) NOT NULL DEFAULT 'open',
  opened_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at        TIMESTAMP,
  CONSTRAINT chk_cash_session_amounts CHECK (
    opening_amount >= 0
    AND (closing_amount IS NULL OR closing_amount >= 0)
    AND (expected_amount IS NULL OR expected_amount >= 0)
  ),
  CONSTRAINT chk_cash_session_status CHECK (status IN ('open', 'closed'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_cash_register_open_session
  ON cash_register_sessions (cash_register_id)
  WHERE status = 'open';

CREATE TABLE IF NOT EXISTS cash_movements (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  local_id      UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  session_id    BIGINT NOT NULL REFERENCES cash_register_sessions(id),
  user_id       INTEGER NOT NULL REFERENCES users(id),
  movement_type VARCHAR(20) NOT NULL,
  amount        NUMERIC(12,2) NOT NULL,
  description   TEXT,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_cash_movement_amount CHECK (amount > 0),
  CONSTRAINT chk_cash_movement_type CHECK (movement_type IN ('income', 'expense'))
);

-- ---------- Dispositivos y sincronización ----------
CREATE TABLE IF NOT EXISTS devices (
  id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  device_uuid  UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  device_name  VARCHAR(100) NOT NULL,
  user_id      INTEGER REFERENCES users(id),
  active       BOOLEAN NOT NULL DEFAULT TRUE,
  last_sync_at TIMESTAMP,
  created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sync_operations (
  id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  operation_uuid    UUID NOT NULL,
  device_id         BIGINT NOT NULL REFERENCES devices(id),
  user_id           INTEGER NOT NULL REFERENCES users(id),
  operation_type    VARCHAR(30) NOT NULL,
  entity_type       VARCHAR(50) NOT NULL,
  entity_id         VARCHAR(100),
  payload           JSONB NOT NULL,
  status            VARCHAR(20) NOT NULL DEFAULT 'pending',
  client_created_at TIMESTAMP NOT NULL,
  received_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  processed_at      TIMESTAMP,
  error_message     TEXT,
  CONSTRAINT uq_sync_operation UNIQUE (device_id, operation_uuid),
  CONSTRAINT chk_sync_operation_status CHECK (status IN ('pending', 'processing', 'synced', 'failed', 'conflict')),
  CONSTRAINT chk_sync_operation_type CHECK (operation_type IN ('create', 'update', 'delete'))
);

CREATE INDEX IF NOT EXISTS idx_sync_operations_status ON sync_operations (status);
CREATE INDEX IF NOT EXISTS idx_sync_operations_device ON sync_operations (device_id);
CREATE INDEX IF NOT EXISTS idx_sync_operations_received ON sync_operations (received_at);

CREATE TABLE IF NOT EXISTS sync_conflicts (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  operation_id  BIGINT NOT NULL REFERENCES sync_operations(id),
  entity_type   VARCHAR(50) NOT NULL,
  entity_id     VARCHAR(100) NOT NULL,
  local_data    JSONB NOT NULL,
  server_data   JSONB NOT NULL,
  resolution    VARCHAR(20) NOT NULL DEFAULT 'pending',
  resolved_data JSONB,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at   TIMESTAMP,
  CONSTRAINT chk_conflict_resolution CHECK (resolution IN ('pending', 'local', 'server', 'merged'))
);

CREATE INDEX IF NOT EXISTS idx_sync_conflicts_resolution ON sync_conflicts (resolution);
